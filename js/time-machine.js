  /* --- Вариант 1: chessboard.js — та же доска, что в дуэли --- */
  function createChessboardBoard(host, fen, opts) {
    if (!host.id) host.id = 'tmq-board-' + Math.random().toString(36).slice(2, 7);
    host.classList.add('tmq-strike');
    host.innerHTML = '';

    var theme = (window.DUEL_BOARD_THEME || CONFIG.pieceTheme);
    var current = fen;

    var board = window.Chessboard(host.id, {
      position: fen,
      draggable: true,
      showNotation: true,
      pieceTheme: theme,
      moveSpeed: 180,
      snapbackSpeed: 140,
      onDragStart: function (source, piece) {
        if (locked) return false;
        var pos = Chess.parse(board.fen());
        /* [FIX] chessboard.js отдаёт фигуру как 'wP' / 'bK'.
           Первая буква — цвет. Раньше здесь сравнивался цвет
           по регистру ('wP' считался чёрным), поэтому ни одна
           фигура не бралась — доска «не нажималась». */
        return String(piece).charAt(0) === pos.turn;
      },
      onDrop: function (source, target) {
        return tryMove(source, target) ? undefined : 'snapback';
      }
    });

    /* ---------- Выбор фигуры нажатием (телефон и мышь) ---------- */
    var selected = null;
    var locked = false;

    function boardEl() {
      return host.querySelector('.board-b72b1') || host;
    }

    function squareFromEvent(ev) {
      var rect = boardEl().getBoundingClientRect();
      if (!rect.width || !rect.height) return null;
      var x = ev.clientX - rect.left;
      var y = ev.clientY - rect.top;
      if (x < 0 || y < 0 || x >= rect.width || y >= rect.height) return null;
      var file = Math.floor(x / (rect.width / 8));
      var rank = 8 - Math.floor(y / (rect.height / 8));
      if (file < 0 || file > 7 || rank < 1 || rank > 8) return null;
      return 'abcdefgh'.charAt(file) + rank;
    }

    function cellOf(sq) {
      return host.querySelector('[data-square="' + sq + '"]');
    }

    function clearHints() {
      Array.prototype.forEach.call(
        host.querySelectorAll('.tmq-hint-sel, .tmq-hint-sq, .tmq-hint-cap'),
        function (el) { el.classList.remove('tmq-hint-sel', 'tmq-hint-sq', 'tmq-hint-cap'); }
      );
      selected = null;
    }

    function selectSquare(sq) {
      clearHints();
      var pos = Chess.parse(board.fen());
      var piece = pos.board[sq];
      if (!piece || Chess.colorOf(piece) !== pos.turn) return false;

      selected = sq;
      var own = cellOf(sq);
      if (own) own.classList.add('tmq-hint-sel');

      Chess.moves(board.fen(), sq).forEach(function (m) {
        var cell = cellOf(m.to);
        if (cell) cell.classList.add(m.capture ? 'tmq-hint-cap' : 'tmq-hint-sq');
      });
      return true;
    }

    function tryMove(from, to) {
      if (locked || !from || !to || from === to) return false;

      var legal = Chess.moves(board.fen(), from).some(function (m) { return m.to === to; });
      if (!legal) return false;

      var ok = !opts.solution || (from === opts.solution.from && to === opts.solution.to);

      if (!ok) {
        locked = true;
        host.classList.remove('is-shake');
        void host.offsetWidth;
        host.classList.add('is-shake');
        if (opts.onResult) opts.onResult(false, from, to);
        setTimeout(function () { locked = false; }, 620);
        return false;
      }

      locked = true;
      board.position(Chess.apply(board.fen(), from, to), false);
      play('playMove');
      if (opts.onResult) setTimeout(function () { opts.onResult(true, from, to); }, 220);
      return true;
    }

    host.addEventListener('click', function (ev) {
      if (locked) return;
      var sq = squareFromEvent(ev);
      if (!sq) return;

      if (selected && sq === selected) { clearHints(); return; }

      if (selected) {
        var legal = Chess.moves(board.fen(), selected).some(function (m) { return m.to === sq; });
        if (legal) {
          tryMove(selected, sq);
          clearHints();
          return;
        }
      }

      if (selectSquare(sq)) play('playMove');
      else clearHints();
    });

    function resize() {
      try { board.resize(); } catch (e) {}
    }
    setTimeout(resize, 60);
    setTimeout(resize, 260);
    window.addEventListener('resize', resize);

    return {
      el: host,
      getFen: function () { return board.fen(); },
      setFen: function (f) { current = f; board.position(f, false); resize(); },
      resize: resize,
      destroy: function () {
        window.removeEventListener('resize', resize);
        try { board.destroy(); } catch (e) {}
      }
    };
  }

  /* --- Вариант 2: встроенная доска, если библиотеки нет --- */
  function createCssBoard(host, fen, opts) {
    var files = 'abcdefgh';
    var curFen = fen;
    var pos = Chess.parse(curFen);
    var selected = null;
    var locked = false;
    var cells = {};

    var grid = document.createElement('div');
    grid.className = 'tmq-board';
    host.innerHTML = '';
    host.appendChild(grid);

    function mkLabel(cls, text) {
      var i = document.createElement('i');
      i.className = 'tmq-lbl ' + cls;
      i.textContent = text;
      return i;
    }

    function paint() {
      grid.innerHTML = '';
      cells = {};
      for (var rank = 8; rank >= 1; rank--) {
        for (var f = 0; f < 8; f++) {
          var sq = files.charAt(f) + rank;
          var cell = document.createElement('button');
          cell.type = 'button';
          cell.className = 'tmq-sq ' + (((f + rank) % 2 === 1) ? 'is-dark' : 'is-light');
          cell.setAttribute('data-sq', sq);
          cell.setAttribute('aria-label', 'Поле ' + sq);

          var piece = pos.board[sq];
          if (piece) {
            var span = document.createElement('span');
            span.className = 'tmq-pc ' + (piece === piece.toUpperCase() ? 'is-w' : 'is-b');
            span.textContent = GLYPH[piece] || '';
            cell.appendChild(span);
          }
          if (f === 0) cell.appendChild(mkLabel('tmq-lbl-rank', String(rank)));
          if (rank === 1) cell.appendChild(mkLabel('tmq-lbl-file', files.charAt(f)));

          cells[sq] = cell;
          grid.appendChild(cell);
        }
      }
    }

    function clearMarks() {
      for (var sq in cells) {
        if (!Object.prototype.hasOwnProperty.call(cells, sq)) continue;
        cells[sq].classList.remove('is-sel');
        var dots = cells[sq].querySelectorAll('.tmq-dot, .tmq-ring');
        for (var i = 0; i < dots.length; i++) dots[i].parentNode.removeChild(dots[i]);
      }
      selected = null;
    }

    function select(sq) {
      clearMarks();
      selected = sq;
      cells[sq].classList.add('is-sel');

      var list = Chess.moves(curFen, sq);
      for (var i = 0; i < list.length; i++) {
        var target = cells[list[i].to];
        if (!target) continue;
        var mark = document.createElement('i');
        mark.className = list[i].capture ? 'tmq-ring' : 'tmq-dot';
        target.appendChild(mark);
      }
      play('playMove');
    }

    function commit(from, to) {
      locked = true;
      clearMarks();

      var correct = !opts.solution || (from === opts.solution.from && to === opts.solution.to);

      if (correct) {
        if (cells[from]) cells[from].classList.add('is-ok-from');
        if (cells[to]) cells[to].classList.add('is-ok-to');

        var next = Chess.apply(curFen, from, to);
        setTimeout(function () {
          curFen = next;
          pos = Chess.parse(curFen);
          paint();
          if (cells[from]) cells[from].classList.add('is-ok-from');
          if (cells[to]) cells[to].classList.add('is-ok-to');
          if (opts.onResult) opts.onResult(true, from, to);
        }, 220);
      } else {
        if (cells[from]) cells[from].classList.add('is-bad-from');
        if (cells[to]) cells[to].classList.add('is-bad-to');
        host.classList.remove('is-shake');
        void host.offsetWidth;
        host.classList.add('is-shake');
        if (opts.onResult) opts.onResult(false, from, to);
        setTimeout(function () {
          for (var sq in cells) {
            if (!Object.prototype.hasOwnProperty.call(cells, sq)) continue;
            cells[sq].classList.remove('is-bad-from', 'is-bad-to');
          }
          locked = false;
        }, 780);
      }
    }

    grid.addEventListener('click', function (e) {
      var cell = e.target.closest ? e.target.closest('.tmq-sq') : null;
      if (!cell || locked) return;
      var sq = cell.getAttribute('data-sq');
      var piece = pos.board[sq];

      if (selected && sq === selected) { clearMarks(); return; }

      if (selected) {
        var list = Chess.moves(curFen, selected);
        for (var i = 0; i < list.length; i++) {
          if (list[i].to === sq) { commit(selected, sq); return; }
        }
      }

      if (piece && Chess.colorOf(piece) === pos.turn) { select(sq); return; }
      clearMarks();
    });

    var sizeTries = 0;
    function syncSize() {
      var w = host.clientWidth || grid.getBoundingClientRect().width;
      if (!w) {
        if (sizeTries++ < 40) requestAnimationFrame(syncSize);
        return;
      }
      grid.style.height = Math.round(w) + 'px';
    }

    paint();
    syncSize();

    if (typeof ResizeObserver !== 'undefined') {
      try {
        var ro = new ResizeObserver(syncSize);
        ro.observe(host);
      } catch (e) {}
    }
    window.addEventListener('resize', syncSize);
    setTimeout(syncSize, 60);

    return {
      el: grid,
      getFen: function () { return curFen; },
      setFen: function (f) {
        curFen = f;
        pos = Chess.parse(f);
        locked = false;
        clearMarks();
        paint();
        syncSize();
      },
      resize: syncSize,
      destroy: function () { host.innerHTML = ''; }
    };
  }

  /* ==========================================================
     ДОСКА ДУЭЛИ — ровно тот же способ игры, что в NetDuel:
     chessboard.js с draggable:false и тап по клетке .square-55d63.
     Перетаскивание отключено намеренно: в дуэли его нет, а в квесте
     drag конфликтовал с обработчиком тапов — фигура «залипала»,
     и верный ход не принимался.
     ========================================================== */
  function createDuelBoard(host, fen, opts) {
    opts = opts || {};
    var $ = window.jQuery;
    var Ctor = window.Chess;

    if (!host) return null;
    if (typeof window.Chessboard !== 'function' || !$ || typeof Ctor !== 'function') return null;

    if (!host.id) host.id = 'tmq-board-' + Math.random().toString(36).slice(2, 7);
    host.classList.add('tmq-strike');
    host.innerHTML = '';

    var game;
    try { game = new Ctor(fen); } catch (e) { return null; }
    if (!game || typeof game.moves !== 'function' || typeof game.get !== 'function') return null;

    var theme = window.DUEL_BOARD_THEME || CONFIG.pieceTheme;
    var board;
    try {
      board = window.Chessboard(host.id, {
        position: fen,
        draggable: false,
        showNotation: true,
        pieceTheme: theme
      });
    } catch (e) {
      return null;
    }
    if (!board) return null;

    var $host = $(host);
    var selected = null;
    var locked = false;
    var HINT = 'tmq-hint-sel tmq-hint-sq tmq-hint-cap';

    function cell(square) {
      return $host.find('[data-square="' + square + '"]');
    }

    function clearHints() {
      $host.find('.tmq-hint-sel, .tmq-hint-sq, .tmq-hint-cap').removeClass(HINT);
      selected = null;
    }

    function shake() {
      host.classList.remove('is-shake');
      void host.offsetWidth;
      host.classList.add('is-shake');
      setTimeout(function () { host.classList.remove('is-shake'); }, 460);
    }

    function select(square) {
      clearHints();
      var piece = game.get(square);
      if (!piece || piece.color !== game.turn()) return false;

      selected = square;
      cell(square).addClass('tmq-hint-sel');
      game.moves({ square: square, verbose: true }).forEach(function (m) {
        cell(m.to).addClass(game.get(m.to) ? 'tmq-hint-cap' : 'tmq-hint-sq');
      });
      play('playMove');
      return true;
    }

    function commit(from, to) {
      var ok = !opts.solution || (from === opts.solution.from && to === opts.solution.to);
      var made;
      try { made = game.move({ from: from, to: to, promotion: 'q' }); } catch (e) { made = null; }
      if (!made) { clearHints(); return; }

      board.position(game.fen(), false);
      clearHints();

      if (ok) {
        locked = true;
        if (opts.onResult) setTimeout(function () { opts.onResult(true, from, to); }, 200);
        return;
      }

      locked = true;
      shake();
      if (opts.onResult) opts.onResult(false, from, to);
      setTimeout(function () {
        try { game.undo(); } catch (e) {}
        board.position(game.fen(), false);
        locked = false;
      }, 620);
    }

    function onSquare(ev) {
      if (locked) return;
      var square = $(ev.currentTarget).attr('data-square');
      if (!square) return;
      if (ev.preventDefault) ev.preventDefault();

      if (selected) {
        if (square === selected) { clearHints(); return; }
        var legal = game.moves({ square: selected, verbose: true })
          .some(function (m) { return m.to === square; });
        if (legal) { commit(selected, square); return; }
      }

      var piece = game.get(square);
      if (piece && piece.color === game.turn()) { select(square); return; }
      clearHints();
    }

    /* Один обработчик на контейнер: срабатывает и на тап, и на клик мышью */
    $host.off('click.tmqBoard', '.square-55d63');
    $host.on('click.tmqBoard', '.square-55d63', onSquare);

    function resize() { try { board.resize(); } catch (e) {} }
    setTimeout(resize, 60);
    setTimeout(resize, 220);

    return {
      el: host,
      getFen: function () { return game.fen(); },
      setFen: function (f) {
        try { game.load(f); } catch (e) {}
        try { board.position(f, false); } catch (e) {}
        clearHints();
        locked = false;
        resize();
      },
      resize: resize,
      destroy: function () {
        $host.off('click.tmqBoard');
        try { board.destroy(); } catch (e) {}
        host.innerHTML = '';
      }
    };
  }

  function createBoard(host, fen, opts) {
    opts = opts || {};
    if (!host) return null;

    try {
      var made = createDuelBoard(host, fen, opts);
      if (made && host.querySelector('.board-b72b1')) return made;
      if (made) {
        console.warn('[TimeMachineQuest] доска дуэли не отрисовалась — включаю встроенную.');
        try { made.destroy(); } catch (e) {}
        host.innerHTML = '';
      }
    } catch (e) {
      console.warn('[TimeMachineQuest] chessboard.js не поднялся, играем на встроенной доске:', e);
      host.innerHTML = '';
    }

    return createCssBoard(host, fen, opts);
  }

